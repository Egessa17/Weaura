create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  admin_id uuid not null references public.users(id) on delete restrict,
  admin_name text not null,
  action text not null,
  entity_type text not null,
  entity_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_audit_logs_created_at_idx
  on public.admin_audit_logs (created_at desc);
create index if not exists admin_audit_logs_admin_id_idx
  on public.admin_audit_logs (admin_id, created_at desc);
create index if not exists admin_audit_logs_entity_idx
  on public.admin_audit_logs (entity_type, entity_id, created_at desc);

alter table public.admin_audit_logs enable row level security;

create policy "Admins can read audit logs"
on public.admin_audit_logs
for select
to authenticated
using (
  exists (
    select 1 from public.users
    where users.id = auth.uid() and users.role = 'admin'
  )
);

alter table public.orders
  add column if not exists status_updated_at timestamptz,
  add column if not exists status_updated_by uuid references public.users(id) on delete set null;

create or replace function public.admin_display_name(p_admin_id uuid)
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(name, split_part(email, '@', 1))
  from public.users
  where id = p_admin_id and role = 'admin';
$$;

revoke all on function public.admin_display_name(uuid) from public, anon, authenticated;

create or replace function public.set_order_status_audit_fields()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid;
begin
  if new.order_status is distinct from old.order_status then
    v_admin_id := coalesce(auth.uid(), new.payment_verified_by, old.payment_verified_by);
    if v_admin_id is not null and public.admin_display_name(v_admin_id) is not null then
      new.status_updated_by := v_admin_id;
      new.status_updated_at := now();
    end if;
  end if;
  return new;
end;
$$;

revoke all on function public.set_order_status_audit_fields() from public, anon, authenticated;

drop trigger if exists set_order_status_audit_fields_trigger on public.orders;
create trigger set_order_status_audit_fields_trigger
before update on public.orders
for each row execute function public.set_order_status_audit_fields();

create or replace function public.audit_order_changes()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid;
  v_admin_name text;
begin
  v_admin_id := coalesce(auth.uid(), new.payment_verified_by, old.payment_verified_by);
  v_admin_name := public.admin_display_name(v_admin_id);
  if v_admin_name is null then
    return new;
  end if;

  if new.payment_status is distinct from old.payment_status then
    insert into public.admin_audit_logs
      (admin_id, admin_name, action, entity_type, entity_id, details)
    values
      (v_admin_id, v_admin_name, 'payment_status_changed', 'order', new.id,
       jsonb_build_object(
         'from', old.payment_status,
         'to', new.payment_status,
         'transaction_id', new.transaction_id,
         'payment_method', new.payment_method
       ));
  end if;

  if new.order_status is distinct from old.order_status then
    insert into public.admin_audit_logs
      (admin_id, admin_name, action, entity_type, entity_id, details)
    values
      (v_admin_id, v_admin_name, 'order_status_changed', 'order', new.id,
       jsonb_build_object('from', old.order_status, 'to', new.order_status));
  end if;

  return new;
end;
$$;

revoke all on function public.audit_order_changes() from public, anon, authenticated;

drop trigger if exists audit_order_changes_trigger on public.orders;
create trigger audit_order_changes_trigger
after update on public.orders
for each row execute function public.audit_order_changes();

create or replace function public.audit_product_changes()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := auth.uid();
  v_admin_name text;
  v_product_id uuid;
  v_action text;
  v_details jsonb;
begin
  v_admin_name := public.admin_display_name(v_admin_id);
  if v_admin_name is null then
    if tg_op = 'DELETE' then return old; else return new; end if;
  end if;

  if tg_op = 'INSERT' then
    v_product_id := new.id;
    v_action := 'product_created';
    v_details := jsonb_build_object('name', new.name, 'price_ugx', new.price, 'stock', new.stock);
  elsif tg_op = 'UPDATE' then
    v_product_id := new.id;
    v_action := 'product_updated';
    v_details := jsonb_build_object(
      'name', new.name,
      'old_price_ugx', old.price,
      'new_price_ugx', new.price,
      'old_stock', old.stock,
      'new_stock', new.stock
    );
  else
    v_product_id := old.id;
    v_action := 'product_deleted';
    v_details := jsonb_build_object('name', old.name, 'price_ugx', old.price, 'stock', old.stock);
  end if;

  insert into public.admin_audit_logs
    (admin_id, admin_name, action, entity_type, entity_id, details)
  values
    (v_admin_id, v_admin_name, v_action, 'product', v_product_id, v_details);

  if tg_op = 'DELETE' then return old; else return new; end if;
end;
$$;

revoke all on function public.audit_product_changes() from public, anon, authenticated;

drop trigger if exists audit_product_changes_trigger on public.products;
create trigger audit_product_changes_trigger
after insert or update or delete on public.products
for each row execute function public.audit_product_changes();

create or replace function public.log_admin_session_event(p_action text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := auth.uid();
  v_admin_name text;
begin
  if p_action not in ('admin_login', 'admin_logout') then
    raise exception 'Unsupported session audit action';
  end if;

  v_admin_name := public.admin_display_name(v_admin_id);
  if v_admin_name is null then
    raise exception 'Admin access required';
  end if;

  insert into public.admin_audit_logs
    (admin_id, admin_name, action, entity_type, details)
  values
    (v_admin_id, v_admin_name, p_action, 'session', '{}'::jsonb);
end;
$$;

revoke all on function public.log_admin_session_event(text) from public, anon;
grant execute on function public.log_admin_session_event(text) to authenticated;
