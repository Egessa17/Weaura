-- Accountable inventory movements, threshold alert state, and safe adjustments.

alter table public.products
  add column if not exists low_stock_alerted boolean not null default false;

create table if not exists public.inventory_movements (
  id bigint generated by default as identity primary key,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  admin_id uuid not null references public.users(id) on delete restrict,
  admin_name text not null,
  order_id uuid references public.orders(id) on delete set null,
  movement_type text not null check (
    movement_type in ('initial_stock', 'restock', 'manual_reduction', 'sale', 'correction')
  ),
  quantity_change integer not null check (quantity_change <> 0),
  before_quantity integer not null check (before_quantity >= 0),
  after_quantity integer not null check (after_quantity >= 0),
  reason text not null,
  created_at timestamptz not null default now()
);

create index if not exists inventory_movements_product_idx
  on public.inventory_movements (product_id, created_at desc);
create index if not exists inventory_movements_admin_idx
  on public.inventory_movements (admin_id, created_at desc);
create index if not exists inventory_movements_order_idx
  on public.inventory_movements (order_id);

alter table public.inventory_movements enable row level security;

create policy "Admins can read inventory movements"
on public.inventory_movements
for select
to authenticated
using (
  exists (
    select 1 from public.users
    where users.id = auth.uid() and users.role = 'admin'
  )
);

create or replace function public.protect_direct_stock_updates()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.stock is distinct from old.stock
     and current_user <> 'postgres' then
    raise exception 'Use the inventory adjustment workflow to change stock';
  end if;
  return new;
end;
$$;

revoke all on function public.protect_direct_stock_updates() from public, anon, authenticated;

drop trigger if exists protect_direct_stock_updates_trigger on public.products;
create trigger protect_direct_stock_updates_trigger
before update on public.products
for each row execute function public.protect_direct_stock_updates();

create or replace function public.record_inventory_movement()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid;
  v_admin_name text;
  v_order_id uuid;
  v_movement_type text;
  v_reason text;
begin
  if new.stock is not distinct from old.stock then
    return new;
  end if;

  v_admin_id := nullif(current_setting('weaura.inventory_admin_id', true), '')::uuid;
  v_admin_id := coalesce(v_admin_id, auth.uid());
  v_admin_name := public.admin_display_name(v_admin_id);
  if v_admin_name is null then
    raise exception 'Inventory change is missing an administrator';
  end if;

  v_order_id := nullif(current_setting('weaura.inventory_order_id', true), '')::uuid;
  v_movement_type := coalesce(
    nullif(current_setting('weaura.inventory_movement_type', true), ''),
    case when new.stock > old.stock then 'restock' else 'manual_reduction' end
  );
  v_reason := coalesce(
    nullif(current_setting('weaura.inventory_reason', true), ''),
    'Inventory adjusted'
  );

  insert into public.inventory_movements (
    product_id, product_name, admin_id, admin_name, order_id,
    movement_type, quantity_change, before_quantity, after_quantity, reason
  ) values (
    new.id, new.name, v_admin_id, v_admin_name, v_order_id,
    v_movement_type, new.stock - old.stock, old.stock, new.stock, v_reason
  );

  insert into public.admin_audit_logs (
    admin_id, admin_name, action, entity_type, entity_id, details
  ) values (
    v_admin_id,
    v_admin_name,
    'inventory_adjusted',
    'product',
    new.id,
    jsonb_build_object(
      'product_name', new.name,
      'movement_type', v_movement_type,
      'quantity_change', new.stock - old.stock,
      'before_quantity', old.stock,
      'after_quantity', new.stock,
      'reason', v_reason,
      'order_id', v_order_id
    )
  );

  if new.stock > 15 then
    new.low_stock_alerted := false;
  end if;

  return new;
end;
$$;

revoke all on function public.record_inventory_movement() from public, anon, authenticated;

drop trigger if exists record_inventory_movement_trigger on public.products;
create trigger record_inventory_movement_trigger
before update of stock on public.products
for each row execute function public.record_inventory_movement();

create or replace function public.record_initial_inventory()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := auth.uid();
  v_admin_name text;
begin
  if new.stock <= 0 then return new; end if;
  v_admin_name := public.admin_display_name(v_admin_id);
  if v_admin_name is null then
    raise exception 'Initial inventory is missing an administrator';
  end if;

  insert into public.inventory_movements (
    product_id, product_name, admin_id, admin_name, movement_type,
    quantity_change, before_quantity, after_quantity, reason
  ) values (
    new.id, new.name, v_admin_id, v_admin_name, 'initial_stock',
    new.stock, 0, new.stock, 'Initial product inventory'
  );
  return new;
end;
$$;

revoke all on function public.record_initial_inventory() from public, anon, authenticated;

drop trigger if exists record_initial_inventory_trigger on public.products;
create trigger record_initial_inventory_trigger
after insert on public.products
for each row execute function public.record_initial_inventory();

create or replace function public.adjust_inventory(
  p_product_id uuid,
  p_quantity_change integer,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_admin_id uuid := auth.uid();
  v_product public.products;
  v_new_stock integer;
  v_alert_needed boolean := false;
begin
  if public.admin_display_name(v_admin_id) is null then
    raise exception 'Admin access required';
  end if;
  if p_quantity_change = 0 then
    raise exception 'Quantity change cannot be zero';
  end if;
  if length(trim(coalesce(p_reason, ''))) < 3 then
    raise exception 'A reason is required';
  end if;

  select * into v_product from public.products where id = p_product_id for update;
  if not found then raise exception 'Product not found'; end if;

  v_new_stock := v_product.stock + p_quantity_change;
  if v_new_stock < 0 then raise exception 'Inventory cannot go below zero'; end if;

  perform set_config('weaura.inventory_admin_id', v_admin_id::text, true);
  perform set_config('weaura.inventory_order_id', '', true);
  perform set_config(
    'weaura.inventory_movement_type',
    case when p_quantity_change > 0 then 'restock' else 'manual_reduction' end,
    true
  );
  perform set_config('weaura.inventory_reason', trim(p_reason), true);

  update public.products set stock = v_new_stock where id = p_product_id
  returning * into v_product;

  if v_product.stock <= 15 and not v_product.low_stock_alerted then
    update public.products set low_stock_alerted = true where id = p_product_id
    returning * into v_product;
    v_alert_needed := true;
  end if;

  return jsonb_build_object(
    'product', to_jsonb(v_product),
    'alert_needed', v_alert_needed
  );
end;
$$;

revoke all on function public.adjust_inventory(uuid, integer, text) from public, anon;
grant execute on function public.adjust_inventory(uuid, integer, text) to authenticated;

create or replace function public.claim_low_stock_alerts(p_product_ids uuid[])
returns setof public.products
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  update public.products
  set low_stock_alerted = true
  where id = any(p_product_ids)
    and stock <= 15
    and low_stock_alerted = false
  returning products.*;
end;
$$;

revoke all on function public.claim_low_stock_alerts(uuid[]) from public, anon, authenticated;
grant execute on function public.claim_low_stock_alerts(uuid[]) to service_role;

-- Replace payment verification so automatic sale subtraction is also recorded.
create or replace function public.verify_order_payment(
  p_order_id uuid,
  p_transaction_id text,
  p_admin_id uuid
)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders;
  v_item jsonb;
  v_product_id uuid;
  v_quantity integer;
begin
  if public.admin_display_name(p_admin_id) is null then
    raise exception 'Admin access required';
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then raise exception 'Order not found'; end if;
  if v_order.payment_status <> 'Awaiting verification' then
    raise exception 'Order payment has already been processed';
  end if;
  if p_transaction_id <> v_order.transaction_id then
    raise exception 'Transaction ID does not match the customer submission';
  end if;
  if (v_order.payment_method = 'MTN MoMo' and p_transaction_id !~ '^[0-9]{11}$')
     or (v_order.payment_method = 'Airtel Money' and p_transaction_id !~ '^[0-9]{12}$')
     or v_order.payment_method not in ('MTN MoMo', 'Airtel Money') then
    raise exception 'Transaction ID format is invalid for the selected provider';
  end if;

  perform set_config('weaura.inventory_admin_id', p_admin_id::text, true);
  perform set_config('weaura.inventory_order_id', p_order_id::text, true);
  perform set_config('weaura.inventory_movement_type', 'sale', true);
  perform set_config('weaura.inventory_reason', 'Verified order sale', true);

  for v_item in select * from jsonb_array_elements(v_order.items)
  loop
    v_product_id := (v_item->>'product_id')::uuid;
    v_quantity := (v_item->>'quantity')::integer;
    if v_quantity < 1 then raise exception 'Invalid item quantity'; end if;

    update public.products
    set stock = stock - v_quantity
    where id = v_product_id and stock >= v_quantity;
    if not found then raise exception 'Insufficient stock for product %', v_product_id; end if;
  end loop;

  update public.orders
  set payment_status = 'Verified',
      payment_verified_at = now(),
      payment_verified_by = p_admin_id,
      order_status = 'Confirmed'
  where id = p_order_id
  returning * into v_order;

  return v_order;
end;
$$;

revoke all on function public.verify_order_payment(uuid, text, uuid) from public, anon, authenticated;
grant execute on function public.verify_order_payment(uuid, text, uuid) to service_role;
